def checksum(px: buffer, n: int) -> int:
    s = 0
    for i in range(n):
        s = (s * 31 + (sys.peek(px, i * 4, 4) & 0xFFFFFF)) % 1000000007
    return s

def farthest(px: buffer, ref: bytes, n: int) -> int:
    """How far the pixels are from djpeg's (R G B bytes), at most."""
    worst = 0
    for i in range(n):
        v = sys.peek(px, i * 4, 4)
        a = sys.peek(px, i * 4 + 3, 1)
        if a != 255:
            return 999
        for k in range(3):
            d = abs(((v >> (16 - 8 * k)) & 255) - ref[i * 3 + k])
            worst = max(worst, d)
    return worst

